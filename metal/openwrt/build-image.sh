#!/bin/bash
# Build a preconfigured OpenWrt image for the gateway (Raspberry Pi 4)
#
# Run on pimaster as root (needs losetup and mount):
#   WIFI_SSID='<home ssid>' WIFI_KEY='<home wifi password>' metal/openwrt/build-image.sh
#
# The official ext4 factory image is downloaded and verified, then
# gateway-setup.sh is added as a first-boot script (/etc/uci-defaults), with the
# pimaster SSH key and a root password. The gateway boots directly on
# 10.0.0.1 (LAN) and 192.168.50.200 (WAN, home Wi-Fi), never on 192.168.1.1.
#
# Optional: OPENWRT_VERSION, SSH_PUBKEY, ROOT_PASSWORD_FILE, OUT_DIR, and the
# gateway-setup.sh overrides (WIFI_COUNTRY, WIFI_BAND, LAN_DHCP, HOME_ROUTER, ...)

set -euo pipefail

: "${WIFI_SSID:?set WIFI_SSID}"
: "${WIFI_KEY:?set WIFI_KEY}"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OPENWRT_VERSION="${OPENWRT_VERSION:-25.12.6}"
SSH_PUBKEY="${SSH_PUBKEY:-$HOME/.ssh/id_rsa.pub}"
# Generated on first build, needed for LuCI
ROOT_PASSWORD_FILE="${ROOT_PASSWORD_FILE:-$HOME/.secrets/openwrt-root-password}"
OUT_DIR="${OUT_DIR:-$SCRIPT_DIR/img}"

TARGET_URL="https://downloads.openwrt.org/releases/$OPENWRT_VERSION/targets/bcm27xx/bcm2711"
IMAGE_GZ="openwrt-$OPENWRT_VERSION-bcm27xx-bcm2711-rpi-4-ext4-factory.img.gz"
IMAGE="$OUT_DIR/openwrt-$OPENWRT_VERSION-gateway.img"

# Single-quote a value for the generated shell script
quote() {
  printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

mkdir -p "$OUT_DIR"
cd "$OUT_DIR"

########################
# Download and verify
########################
if [ ! -f "$IMAGE_GZ" ]; then
  curl -fsSLO "$TARGET_URL/$IMAGE_GZ"
fi
curl -fsSL "$TARGET_URL/sha256sums" | grep " \*$IMAGE_GZ\$" | sed 's/ \*/  /' | sha256sum -c -

# OpenWrt images have trailing data after the gzip stream: gunzip exits 2
gunzip -c "$IMAGE_GZ" > "$IMAGE" || [ $? -eq 2 ]

########################
# Root password
########################
if [ ! -s "$ROOT_PASSWORD_FILE" ]; then
  mkdir -p "$(dirname "$ROOT_PASSWORD_FILE")"
  (umask 077 && openssl rand -base64 18 > "$ROOT_PASSWORD_FILE")
  echo "[INFO] Generated root password in $ROOT_PASSWORD_FILE"
fi
ROOT_HASH="$(openssl passwd -6 -stdin < "$ROOT_PASSWORD_FILE")"

########################
# Customize rootfs
########################
MNT="$(mktemp -d)"
LOOP="$(losetup -fP --show "$IMAGE")"
cleanup() {
  umount "$MNT" 2>/dev/null || true
  losetup -d "$LOOP" 2>/dev/null || true
  rmdir "$MNT"
}
trap cleanup EXIT

mount "${LOOP}p2" "$MNT"

# SSH key: gateway-setup.sh disables password login when it is present
install -m 600 "$SSH_PUBKEY" "$MNT/etc/dropbear/authorized_keys"

sed -i "s|^root:[^:]*:|root:$ROOT_HASH:|" "$MNT/etc/shadow"

# No DHCP server even if the first-boot script fails: the LAN shares the
# segment with the home network
if [ "${LAN_DHCP:-0}" != "1" ]; then
  sed -i "/^config dhcp '\?lan'\?$/a\\	option ignore '1'" "$MNT/etc/config/dhcp"
fi

# First boot: uci-defaults are sourced in a subshell and removed on success
{
  echo "# Generated by build-image.sh"
  echo "NO_REBOOT=1"
  for var in WIFI_SSID WIFI_KEY WIFI_COUNTRY WIFI_BAND LAN_DHCP HOME_NET HOME_ROUTER WAN_IP; do
    [ -n "${!var:-}" ] && echo "$var=$(quote "${!var}")"
  done
  sed '1d' "$SCRIPT_DIR/gateway-setup.sh"
} > "$MNT/etc/uci-defaults/99-gateway-setup"
chmod 600 "$MNT/etc/uci-defaults/99-gateway-setup"

sync
echo "[INFO] Image ready: $IMAGE"
